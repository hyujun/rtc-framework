#!/bin/bash
# setup_vcan.sh — 개발 PC 용 가상 CAN FD 인터페이스 (vcan0, MTU 72)
#
# rtc_communication 의 CAN / CAN FD 테스트 (설치 헤더 testing/can_test_support.hpp 의
# SKIP_IF_NO_FD_VCAN) 와 udp_hand_driver 의 proto2 SIL (`sil_mode:=firmware`,
# vcan0) 이 요구하는 인터페이스를 만든다. CAN FD 프레임 (canfd_frame, 72 B) 을
# 실으려면 MTU 가 CANFD_MTU = 72 여야 하고, vcan 의 기본 MTU 는 커널에 따라
# 다르다 (7.0.0-38-generic 실측 2060 = CAN XL; 옛 커널은 16 = classic).
#
# 멱등성: 모듈 · 인터페이스 · MTU · UP 각각 현재 상태를 보고 필요한 것만 바꾼다.
# 재부팅 뒤에도 남도록 systemd oneshot (rtc-vcan-<iface>.service) 을 등록한다
# (setup_udp_optimization.sh Step 5 와 같은 패턴, --no-persist 로 생략).
#
# Usage:
#   sudo ./setup_vcan.sh                 # vcan0
#   sudo ./setup_vcan.sh vcan1           # 다른 이름
#   sudo ./setup_vcan.sh --no-persist    # 이번 부팅만
#   sudo ./setup_vcan.sh --remove        # 인터페이스 · 서비스 제거
#
# 검증:
#   ip -details link show vcan0                      # mtu 72 (state UNKNOWN 이 정상 — vcan 은 carrier 가 없다)
#   candump vcan0 &  cansend vcan0 123##1DEADBEEF    # can-utils: sudo apt install can-utils
#   colcon test --packages-select rtc_communication  # CAN FD loopback 이 SKIP 이 아니어야 한다
#
# 테스트 훅: RTC_ETC_ROOT=<dir> 이면 /usr/local/bin · /etc/systemd/system 을 그
# 아래에 쓰고 root 를 요구하지 않는다 (test/test_can_setup.sh — ip · modprobe ·
# systemctl 은 stub). RTC_SYSFS_ROOT (기본 /sys) 로 인터페이스 상태를 읽는다.

set -euo pipefail

# ── 공통 라이브러리 로드 ────────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/rt_common.sh
source "${SCRIPT_DIR}/lib/rt_common.sh"
make_logger "VCAN"

readonly CANFD_MTU=72

usage() {
  echo ""
  echo "Usage: sudo setup_vcan.sh [IFACE] [--no-persist] [--remove]"
  echo ""
  echo "  IFACE         인터페이스 이름 (기본 vcan0)"
  echo "  --no-persist  systemd 서비스를 만들지 않는다 (이번 부팅만)"
  echo "  --remove      인터페이스와 서비스를 제거한다"
  echo "  -h, --help    도움말"
  echo ""
  exit 0
}

# ── 인자 파싱 ───────────────────────────────────────────────────────────────
IFACE="vcan0"
PERSIST=1
REMOVE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help|help) usage ;;
    --no-persist)   PERSIST=0 ;;
    --remove)       REMOVE=1 ;;
    -*)             fatal "Unknown option: $1 (see --help)" ;;
    *)              IFACE="$1" ;;
  esac
  shift
done

ETC_ROOT="${RTC_ETC_ROOT:-}"
[[ -n "$ETC_ROOT" ]] || require_root
SYS_ROOT="${RTC_SYSFS_ROOT:-/sys}"
BIN_DIR="${ETC_ROOT}/usr/local/bin"
SYSTEMD_DIR="${ETC_ROOT}/etc/systemd/system"
APPLY_SCRIPT="${BIN_DIR}/rtc-vcan-${IFACE}.sh"
SERVICE="rtc-vcan-${IFACE}.service"
SERVICE_PATH="${SYSTEMD_DIR}/${SERVICE}"

# ── 현재 상태 (sysfs) ───────────────────────────────────────────────────────
iface_present() { [[ -d "${SYS_ROOT}/class/net/${IFACE}" ]]; }
iface_mtu()     { cat "${SYS_ROOT}/class/net/${IFACE}/mtu" 2>/dev/null || echo 0; }
iface_is_up()   {
  local flags
  flags=$(cat "${SYS_ROOT}/class/net/${IFACE}/flags" 2>/dev/null || echo 0)
  (( (flags & 0x1) != 0 ))   # IFF_UP
}

# ── --remove ────────────────────────────────────────────────────────────────
if [[ "$REMOVE" -eq 1 ]]; then
  section "Removing ${IFACE}..."
  if iface_present; then
    ip link del dev "$IFACE"
    info "  ${IFACE} deleted"
  else
    info "  ${IFACE} not present — skipped"
  fi
  if [[ -f "$SERVICE_PATH" ]]; then
    systemctl disable "$SERVICE" 2>/dev/null || true
    rm -f "$SERVICE_PATH" "$APPLY_SCRIPT"
    systemctl daemon-reload
    info "  ${SERVICE} removed"
  fi
  exit 0
fi

# ── 1. 인터페이스 (멱등) ────────────────────────────────────────────────────
section "Step 1: ${IFACE} (virtual CAN, MTU ${CANFD_MTU})..."
if ! iface_present; then
  modprobe vcan
  ip link add dev "$IFACE" type vcan
  info "  ${IFACE} created"
else
  info "  ${IFACE} already exists — skipped"
fi

MTU="$(iface_mtu)"
# sysfs 를 바꾼 직후 (방금 만든 인터페이스 · stub) 는 읽을 수 없을 수 있다 → 0 이면 설정한다
if [[ "$MTU" -ne "$CANFD_MTU" ]]; then
  # MTU 변경은 down 상태에서만 허용되는 드라이버가 있다 — vcan 도 같은 경로로 간다
  ip link set "$IFACE" down
  ip link set "$IFACE" mtu "$CANFD_MTU"
  info "  mtu ${MTU} → ${CANFD_MTU} (CAN FD)"
  ip link set "$IFACE" up
  info "  ${IFACE} up"
elif ! iface_is_up; then
  ip link set "$IFACE" up
  info "  ${IFACE} up"
else
  info "  mtu ${CANFD_MTU}, up — already optimal"
fi

# ── 2. systemd persistence ──────────────────────────────────────────────────
# vcan 인터페이스는 재부팅에 사라진다. 생성 스크립트 + oneshot 으로 재적용한다.
if [[ "$PERSIST" -eq 1 ]]; then
  section "Step 2: systemd persistence (${SERVICE})..."
  install -d "$BIN_DIR" "$SYSTEMD_DIR"

  APPLY_CONTENT="#!/bin/bash
# Re-create ${IFACE} (virtual CAN FD, MTU ${CANFD_MTU}) after boot
# Generated by setup_vcan.sh — do not edit manually
set -e
IFACE=\"${IFACE}\"
modprobe vcan
ip link show \"\$IFACE\" &>/dev/null || ip link add dev \"\$IFACE\" type vcan
ip link set \"\$IFACE\" down
ip link set \"\$IFACE\" mtu ${CANFD_MTU}
ip link set \"\$IFACE\" up"

  if write_file_if_changed "$APPLY_SCRIPT" "$APPLY_CONTENT" false; then
    chmod +x "$APPLY_SCRIPT"
    info "  Script written to ${APPLY_SCRIPT}"
  else
    info "  ${APPLY_SCRIPT} already up-to-date — skipped"
  fi

  SERVICE_CONTENT="[Unit]
Description=Virtual CAN FD interface ${IFACE} (RTC tests, proto2 SIL)
After=network-pre.target

[Service]
Type=oneshot
ExecStart=${APPLY_SCRIPT}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target"

  if write_file_if_changed "$SERVICE_PATH" "$SERVICE_CONTENT" false; then
    info "  Service written to ${SERVICE_PATH}"
  else
    info "  ${SERVICE_PATH} already up-to-date — skipped"
  fi

  systemctl daemon-reload
  systemctl enable "$SERVICE" 2>/dev/null || true
  info "  ${SERVICE} enabled (${IFACE} persists across reboots)"
fi

echo ""
info "${IFACE} ready."
info "  ip -details link show ${IFACE}      # mtu ${CANFD_MTU}"
info "  candump ${IFACE}                     # can-utils"
