def _tier_range_label(m: Manifest, tier: Tier) -> str:
    low, high = m.tier_range(tier)
    if tier is m.tiers[0]:
        return f"≤{high}" if high is not None else f"{low}+"
    if high is None:
        return f"{low}+"
    return f"{low}–{high}"


def emit_doc_matrix(m: Manifest) -> str:
    """rtc_base/README.md — role × tier slot matrix."""
    doc = m.doc
    header_suffix = {int(k): v for k, v in doc.get("tier_header_suffixes", {}).items()}
    label_suffix = doc.get("role_label_suffixes", {})
    cell_suffix = doc.get("cell_suffixes", {})
    unpinned = doc.get("unpinned_cell", "-1")

    headers = ["스레드"] + [f"{t.id}코어{header_suffix.get(t.id, '')}" for t in m.tiers]
    rows = ["| " + " | ".join(headers) + " |"]
    rows.append("|" + "|".join(["--------"] + ["-------"] * len(m.tiers)) + "|")

    for key in _thread_role_keys(m):
        if all(t.specs.get(key) is None for t in m.tiers):
            continue
        ref = next(t.specs[key] for t in reversed(m.tiers) if t.specs.get(key) is not None)
        if ref.policy == "OTHER":
            sched = f"CFS {ref.nice}"
        else:
            sched = f"{ref.policy} {ref.priority}"
        label = f"**{_thread_name(m, key)}** ({sched}{label_suffix.get(key, '')})"
        cells = []
        for tier in m.tiers:
            spec = tier.specs.get(key)
            if spec is None:
                cells.append("—")
            elif spec.slot < 0:
                cells.append(unpinned)
            else:
                cells.append(f"Core {spec.slot}{cell_suffix.get(f'{tier.id}|{key}', '')}")
        rows.append("| " + " | ".join([label] + cells) + " |")
    return "\n".join(rows)


def emit_doc_tiers(m: Manifest) -> str:
    """repo_scripts/README.md — per-tier helper outputs."""
    rows = [
        "| tier (물리 코어) | `get_rt_cores()` | `get_mpc_cores()` | `get_nrt_cores()`"
        " | `get_os_cores()` | arm / hand slot |",
        "|---|---|---|---|---|---|",
    ]
    for tier in m.tiers:
        rows.append(
            "| {label} | `{rt}` | `{mpc}` | `{nrt}` | `{os}` | {arm} / {hand} |".format(
                label=_tier_range_label(m, tier),
                rt=_csv(rt_cores(m, tier)),
                mpc=_csv(mpc_cores(m, tier)),
                nrt=_csv(nrt_cores(m, tier)),
                os=m.os_slot,
                arm=tier.specs["arm_driver"].slot,
                hand=tier.specs["hand_driver"].slot,
            )
        )
    return "\n".join(rows)


_DOC_EMITTERS = {
    "thread-layout-matrix": emit_doc_matrix,
    "thread-layout-tiers": emit_doc_tiers,
}


def _begin(block: str) -> str:
    return f"<!-- BEGIN GENERATED: {block} -->"


def _end(block: str) -> str:
    return f"<!-- END GENERATED: {block} -->"


def render_doc(m: Manifest, path: Path, block: str, text: str | None = None) -> str:
    """Return ``path``'s content with ``block`` refreshed from the manifest.

    ``text`` carries the result of an earlier block in the same file; without it
    a second block would be rendered against the on-disk text and the first
    block's refresh would be dropped on the floor.
    """
    if text is None:
        text = path.read_text(encoding="utf-8")
    begin, end = _begin(block), _end(block)
    if begin not in text or end not in text:
        raise SystemExit(
            f"{path.relative_to(REPO_ROOT)}: missing marker pair for block '{block}'.\n"
            f"  Wrap the table with:\n    {begin}\n    ...\n    {end}"
        )
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    body = _DOC_EMITTERS[block](m)
    note = (
        "<!-- Generated from repo_scripts/config/thread_layout.yaml by"
        " repo_scripts/scripts/gen_thread_layout.py. Do not edit by hand. -->"
    )
    return f"{head}{begin}\n{note}\n\n{body}\n\n{end}{tail}"


# ── driver ──────────────────────────────────────────────────────────────────


def build_targets(m: Manifest) -> tuple[dict[Path, str], list[str]]:
    """Return ``{path: expected content}`` plus the artifacts that had to be skipped.

    The C++ artifact is piped through clang-format so the checked-in file is
    byte-identical to what the repo's PostToolUse format hook would produce --
    otherwise the first person to open the header would make ``--check`` fail.
    That makes clang-format a prerequisite for emitting C++: when it is missing
    the artifact is reported as skipped rather than compared against unformatted
    text (a false STALE). Its values stay covered by the compiler and by
    rtc_base/test/test_mpc_thread_config.cpp.
    """
    skipped: list[str] = []
    targets: dict[Path, str] = {
        REPO_ROOT / m.outputs["shell"]: emit_shell(m),
        REPO_ROOT / m.outputs["python"]: emit_python(m),
    }
    cpp_path = REPO_ROOT / m.outputs["cpp"]
    formatted = _clang_format(emit_cpp(m), cpp_path)
    if formatted is None:
        skipped.append(f"{cpp_path.relative_to(REPO_ROOT)} (clang-format unavailable)")
    else:
        targets[cpp_path] = formatted
    for entry in m.doc_blocks:
        path = REPO_ROOT / entry["file"]
        # Chain, never overwrite: two blocks in one file must both survive.
        targets[path] = render_doc(m, path, entry["block"], targets.get(path))
    return targets, skipped


# Formatter lookup mirrors .claude/hooks/format-code.sh. That hook keeps
# reformatting these artifacts on boxes without a system binary -- it falls back
# to the pinned clang-format through uvx and finds ruff inside the workspace
# venv -- so a generator that only consulted PATH would stop gating precisely
# the files the hook keeps rewriting.
_CLANG_FORMAT_PIN = "18.1.8"  # keep in sync with .claude/hooks/format-code.sh


def _clang_format_candidates(path: Path) -> list[list[str]]:
    tail = ["--style=file", f"--assume-filename={path}"]
    return [
        ["clang-format", *tail],
        ["uvx", "--from", f"clang-format=={_CLANG_FORMAT_PIN}", "clang-format", *tail],
    ]


def _ruff_candidates(target: str) -> list[list[str]]:
    tail = ["format", "--stdin-filename", target, "-"]
    candidates: list[list[str]] = []
    venv = os.environ.get("VIRTUAL_ENV")
    if venv:
        candidates.append([str(Path(venv) / "bin" / "ruff"), *tail])
    # <rtc_ws>/.venv, the isolated env install.sh creates beside this checkout.
    candidates.append([str(REPO_ROOT.parents[1] / ".venv" / "bin" / "ruff"), *tail])
    candidates.append(["ruff", *tail])
    return candidates


def _run_formatter(candidates: list[list[str]], text: str) -> tuple[str | None, str | None]:
    """Run the first available formatter; return ``(stdout, error)``.

    ``(None, None)`` means no candidate exists at all -- a skip, not a failure.
    """
    error: str | None = None
    for argv in candidates:
        # uvx may have to download the pinned release on its first run.
        timeout = 120 if argv[0] == "uvx" else 60
        try:
            result = subprocess.run(
                argv, input=text, capture_output=True, text=True, check=False, timeout=timeout
            )
        except FileNotFoundError:
            continue
        except subprocess.TimeoutExpired:
            error = f"{argv[0]} timed out after {timeout}s"
            continue
        if result.returncode == 0:
            return result.stdout, None
        error = f"{argv[0]} failed: {result.stderr.strip()[:200]}"
    return None, error


def _clang_format(text: str, path: Path) -> str | None:
    formatted, _ = _run_formatter(_clang_format_candidates(path), text)
    return formatted


def run_check(m: Manifest) -> int:
    targets, skipped = build_targets(m)
    stale: list[str] = []
    for path, expected in targets.items():
        rel = path.relative_to(REPO_ROOT)
        if not path.exists():
            stale.append(f"  MISSING  {rel}")
        elif path.read_text(encoding="utf-8") != expected:
            stale.append(f"  STALE    {rel}")
    for note in skipped:
        print(f"thread layout: SKIPPED {note}", file=sys.stderr)
    if stale:
        print("thread layout artifacts are out of sync with the manifest:", file=sys.stderr)
        print("\n".join(stale), file=sys.stderr)
        print(
            "\nThe manifest is the single source of truth "
            "(repo_scripts/config/thread_layout.yaml).\n"
            "Do not edit the generated files: run\n"
            "  python3 repo_scripts/scripts/gen_thread_layout.py --write\n"
            "and commit the result alongside the manifest change.",
            file=sys.stderr,
        )
        return 1
    print(f"thread layout: {len(targets)} artifacts in sync with the manifest")
    return 0


def run_write(m: Manifest) -> int:
    targets, skipped = build_targets(m)
    if skipped:
        for note in skipped:
            print(f"cannot generate {note}", file=sys.stderr)
        print(
            "Install clang-format (apt install clang-format, or uv so the pinned "
            f"clang-format=={_CLANG_FORMAT_PIN} can run through uvx) and re-run --write: "
            "emitting unformatted C++ would make --check fail everywhere else.",
            file=sys.stderr,
        )
        return 1
    changed = 0
    for path, expected in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == expected:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
        changed += 1
    if changed == 0:
        print("thread layout: already up to date")
    return 0


def _formatter_clean(candidates: list[list[str]], text: str, label: str) -> str | None:
    """Run a formatter over ``text``; return its output, or None when unavailable."""
    formatted, error = _run_formatter(candidates, text)
    if formatted is None:
        print(f"  skip  {label}: {error or 'formatter unavailable'}")
    return formatted


def run_self_test(m: Manifest) -> int:
    """Assert the emitters are formatter-idempotent and internally consistent."""
    failures: list[str] = []

    # 1. Every artifact round-trips through --write/--check without change.
    targets, _ = build_targets(m)
    for path, expected in targets.items():
        if path.exists() and path.read_text(encoding="utf-8") != expected:
            failures.append(f"{path.relative_to(REPO_ROOT)} differs from the manifest")

    # 2. The emitted C++ is already clang-format output (build_targets pipes it
    #    through), so a second pass must be a no-op -- otherwise clang-format is
    #    not idempotent here and the format hook could still make --check fail.
    cpp = targets.get(REPO_ROOT / m.outputs["cpp"])
    if cpp is not None:
        formatted = _formatter_clean(
            _clang_format_candidates(REPO_ROOT / m.outputs["cpp"]), cpp, "clang-format"
        )
        if formatted is not None and formatted != cpp:
            failures.append("emit_cpp output is not clang-format stable")

    py = emit_python(m)
    formatted = _formatter_clean(_ruff_candidates(m.outputs["python"]), py, "ruff format")
    if formatted is not None and formatted != py:
        failures.append("emit_python output is not ruff-format stable")

    # 3. Dispatch agrees across the three languages for every sampled core count.
    for ncpu in list(range(1, 18)) + [24, 32, 64]:
        tier = m.tier_for(ncpu)
        if tier.specs["rt_control"].slot < 0:
            failures.append(f"ncpu={ncpu}: rt_control must be pinned")
        rt = rt_cores(m, tier)
        if len(set(rt)) != len(rt):
            failures.append(f"ncpu={ncpu}: RT slots collide: {rt}")

    # 4. Structural invariants the layout must keep on every tier.
    for tier in m.tiers:
        mpc_main = tier.specs["mpc_main"]
        rt_cb = tier.specs["rt_callback"]
        if mpc_main.policy != "OTHER" and mpc_main.priority >= rt_cb.priority:
            failures.append(f"tier {tier.id}: mpc_main priority >= rt_callback")
        for index in range(tier.num_workers):
            worker = tier.specs[f"mpc_worker_{index}"]
            if worker.priority > mpc_main.priority:
                failures.append(f"tier {tier.id}: mpc_worker_{index} priority > mpc_main")
        # arm/hand must not land on an RT controller slot -- the same rule
        # ValidateSystemThreadConfigs() enforces, asserted here because that
        # validator range-checks slots against *this host's* core count, so the
        # C++ test can only reach tiers the host is big enough to represent. A
        # bad slot on the 12/14/16-core tiers would otherwise ship green from
        # every gate and only surface on a deployment box.
        rt_slots = {slot for slot in rt_cores(m, tier) if slot >= 0}
        for role in ("arm_driver", "hand_driver"):
            slot = tier.specs[role].slot
            if slot >= 0 and slot in rt_slots:
                failures.append(
                    f"tier {tier.id}: {role} slot {slot} collides with an RT controller slot"
                )

    if failures:
        print("self-test FAILED:", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1
    print("self-test passed")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument(
        "--check",
        action="store_true",
        help="verify the checked-in artifacts match the manifest (default)",
    )
    group.add_argument("--write", action="store_true", help="regenerate the artifacts")
    group.add_argument(
        "--self-test", action="store_true", help="verify the generator's own invariants"
    )
    args = parser.parse_args(argv)

    manifest = load_manifest()
    if args.write:
        return run_write(manifest)
    if args.self_test:
        return run_self_test(manifest)
    return run_check(manifest)


if __name__ == "__main__":
    sys.exit(main())
