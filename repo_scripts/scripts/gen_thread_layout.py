def emit_python(m: Manifest) -> str:
    out: list[str] = ['"""' + GENERATED_BANNER_LINES[0]]
    for line in GENERATED_BANNER_LINES[1:]:
        out.append(line)
    out += [
        "",
        "Full per-tier role table mirrored for launch-time ``taskset`` pinning.",
        "``rtc_tools.launch.thread_layout`` is the hand-written adapter that exposes",
        "the stable public API on top of this table.",
        "",
        "Every ``slot`` is a ThreadConfig::cpu_core *slot index*, not a kernel logical",
        'CPU id; ``-1`` means "do not pin".',
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class RoleSpec(NamedTuple):",
        '    """One role\'s placement on one tier."""',
        "",
        "    slot: int",
        "    policy: str",
        "    priority: int",
        "    nice: int",
        "",
        "",
        f'LAYOUT_VERSION = "{m.layout_version}"',
        f"OS_SLOT = {m.os_slot}",
        f"MAX_WORKERS = {m.max_workers}",
        "",
        "# Dispatch order: the first tier whose threshold is met wins; the last entry",
        "# is the fallback used below every threshold.",
        "TIER_THRESHOLDS: tuple[tuple[int, int], ...] = (",
    ]
    tiers_desc = m.tiers_desc
    for tier in tiers_desc[:-1]:
        out.append(f"    ({tier.min_cores}, {tier.id}),")
    out += [
        ")",
        f"FALLBACK_TIER = {tiers_desc[-1].id}",
        "",
        "ROLE_SPECS: dict[int, dict[str, RoleSpec]] = {",
    ]
    for tier in m.tiers:
        out.append(f"    {tier.id}: {{")
        for key in _thread_role_keys(m):
            spec = tier.specs.get(key)
            if spec is None:
                continue
            out.append(
                f'        "{key}": RoleSpec({spec.slot}, "{spec.policy}", '
                f"{spec.priority}, {spec.nice}),"
            )
        out.append("    },")
    out += [
        "}",
        "",
        "",
        "def tier_for_cores(physical_cores: int) -> int:",
        '    """Return the tier id used for ``physical_cores`` physical cores."""',
        "    for threshold, tier_id in TIER_THRESHOLDS:",
        "        if physical_cores >= threshold:",
        "            return tier_id",
        "    return FALLBACK_TIER",
        "",
        "",
        "def role_spec(role: str, physical_cores: int) -> RoleSpec | None:",
        '    """Placement of ``role`` at ``physical_cores``; ``None`` if absent there."""',
        "    return ROLE_SPECS[tier_for_cores(physical_cores)].get(role)",
    ]
    return "\n".join(out) + "\n"


